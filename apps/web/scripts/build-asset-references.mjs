#!/usr/bin/env node
// Freeze the site's literal asset references into src/data/asset-references.ts,
// and refuse to build if a new call site has escaped protection.
//
//   node scripts/build-asset-references.mjs           # write the file
//   node scripts/build-asset-references.mjs --check   # verify (runs in build)
//
// Why generated rather than scanned at request time: the cleanup screen has to
// know which keys the code mentions, and a deployed function has no source tree
// to read. So the answer is computed here, committed, and checked on every
// build — the same arrangement as content/_schema/asset-keys.json.
//
// The --check half is [10]'s highest-value control. A page that starts drawing
// a folder through `assetsUnder(...)`, or building a key from a template
// literal, makes files the scan cannot see; without this the cleanup screen
// would quietly offer them for deletion.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scanSource } from "../src/lib/admin/scan-references.ts";
import {
  DYNAMIC_ASSET_SITES,
  PROTECTED_PREFIXES,
} from "../src/lib/admin/protected-prefixes.ts";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, "..", "src");
const outFile = join(srcDir, "data", "asset-references.ts");

const scan = scanSource(srcDir);

// --- the guard --------------------------------------------------------------

const problems = [];
const protectedPrefixes = new Set(PROTECTED_PREFIXES.map(({ prefix }) => prefix));

for (const prefix of scan.prefixes) {
  if (!protectedPrefixes.has(prefix)) {
    problems.push(
      `assetsUnder("${prefix}") draws a whole folder, but "${prefix}" is not in PROTECTED_PREFIXES.\n` +
        "  Add it to src/lib/admin/protected-prefixes.ts, or the cleanup screen will offer those files for deletion.",
    );
  }
}

const acknowledged = new Map(DYNAMIC_ASSET_SITES.map((site) => [site.file, site.covers]));
for (const file of scan.dynamicFiles) {
  const covers = acknowledged.get(file);
  if (!covers) {
    problems.push(
      `${file} builds an asset key at runtime, and no scan can see which files it reaches.\n` +
        "  Add it to DYNAMIC_ASSET_SITES in src/lib/admin/protected-prefixes.ts, with the folders it uses.",
    );
    continue;
  }
  for (const prefix of covers) {
    if (!protectedPrefixes.has(prefix)) {
      problems.push(`${file} is listed as covering "${prefix}", which is not protected.`);
    }
  }
}

for (const { file } of DYNAMIC_ASSET_SITES) {
  if (!scan.dynamicFiles.includes(file)) {
    problems.push(
      `${file} is listed in DYNAMIC_ASSET_SITES but no longer builds a key at runtime.\n` +
        "  Remove the entry (and its prefixes, if nothing else needs them).",
    );
  }
}

if (problems.length > 0) {
  console.error("Asset protection check failed:\n");
  for (const problem of problems) console.error(`  ${problem}\n`);
  process.exit(1);
}

// --- the generated file -----------------------------------------------------

const rendered = `${[
  "// Generated by scripts/build-asset-references.mjs — do not edit by hand.",
  "//",
  "// Every asset key written out in full anywhere in src/. The cleanup screen",
  "// subtracts these (and the content files, read live) from the bucket to find",
  "// what nothing points at any more.",
  "",
  "export const SOURCE_KEYS: readonly string[] = [",
  ...scan.keys.map((key) => `  ${JSON.stringify(key)},`),
  "];",
].join("\n")}\n`;

const check = process.argv.includes("--check");
const current = safeRead(outFile);

if (check) {
  if (current !== rendered) {
    console.error("src/data/asset-references.ts is out of date.");
    console.error("  run: pnpm --filter web build-asset-references");
    process.exit(1);
  }
  console.log(
    `ok      ${scan.keys.length} literal asset keys, ${scan.prefixes.length} folders, ${scan.dynamicFiles.length} runtime call sites`,
  );
} else if (current === rendered) {
  console.log(`unchanged — ${scan.keys.length} literal asset keys`);
} else {
  writeFileSync(outFile, rendered);
  console.log(`wrote src/data/asset-references.ts — ${scan.keys.length} literal asset keys`);
}

function safeRead(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}
